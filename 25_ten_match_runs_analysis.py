# Program 25: Analyze runs scored in 10 matches
runs = (45, 78, 32, 90, 56, 100, 67, 23, 88, 75)

total = sum(runs)
highest = max(runs)
lowest = min(runs)
average = total / len(runs)

print("Total runs:", total)
print("Highest score:", highest)
print("Lowest score:", lowest)
print("Average score:", average)
